/**
 * Coverage manifest: `docs-snippets/coverage.json`, one entry per snippet id, generated from the marker lint and the step
 * registry. It says for every id how the suite covers it:
 *
 *   live          a step runs it against the service and asserts the effect
 *   compile-only  type checked only: import-only snippets, and the browser sources of tsconfig.browser.json
 *   stub          not run and not compiled here: React and React Native sources, which cannot run in this repository (the SDK has no
 *                 React or React Native dependencies), and the documented `stub()` steps of pages that need a browser or React Native
 *
 * `npm run docs-snippets:manifest -- --check` fails on a marker id without a step, a step id without a marker, a duplicate id
 * or a stale coverage.json. It also reports, without failing, docs ids missing from the manifest and manifest ids that no
 * docs page uses. Docs ids come from `<EmbeddedCode>` tags under docs/sdks/javascript of
 * the docs checkout in DOCS_SNIPPETS_DOCS_DIR (default: a `documentation` checkout next to this repository).
 */
import fs from 'node:fs';
import path from 'node:path';
import type { LintResult } from './lint-markers.js';
import type { Registry } from './registry.js';

export interface ManifestEntry {
  file: string | null;
  step: string | null;
  role: string | null;
  phase: string | null;
  mode: 'live' | 'compile-only' | 'stub';
  reason: string | null;
}

export interface Manifest {
  $comment: string;
  snippets: Record<string, ManifestEntry>;
}

/** Sources type checked by tsconfig.browser.json. Keep in sync with its `include`. */
const BROWSER_CHECKED = [
  'quickstarts/quickstart-web.ts',
  'quickstarts/browser-download-file.ts',
  'quickstarts/browser-shared-worker.ts',
];

export function buildManifest(lint: LintResult, reg: Registry): { manifest: Manifest; problems: string[] } {
  const problems: string[] = [];
  const entries: Record<string, ManifestEntry> = {};
  const seen = new Map<string, string>();
  for (const snippet of lint.snippets) {
    const previous = seen.get(snippet.id);
    if (previous) problems.push(`duplicate snippet id ${snippet.id} (${previous} and ${snippet.file})`);
    seen.set(snippet.id, snippet.file);
    if (snippet.step) {
      const def = reg.get(snippet.step);
      if (!def) {
        problems.push(`marker ${snippet.id} sits in step ${snippet.step}, which the registry does not know`);
        continue;
      }
      entries[snippet.id] = {
        file: snippet.file,
        step: def.id,
        role: def.keyset,
        phase: def.phase,
        mode: def.skipIf ? 'compile-only' : 'live',
        reason: def.skipIf ?? null,
      };
    } else if (snippet.importOnly) {
      entries[snippet.id] = {
        file: snippet.file,
        step: null,
        role: null,
        phase: null,
        mode: 'compile-only',
        reason: 'import-only snippet, type checked by tsconfig.live.json',
      };
    } else if (snippet.file.startsWith('quickstarts/')) {
      const browser = BROWSER_CHECKED.includes(snippet.file);
      entries[snippet.id] = {
        file: snippet.file,
        step: null,
        role: null,
        phase: null,
        mode: browser ? 'compile-only' : 'stub',
        reason: browser
          ? 'browser-only, type checked by tsconfig.browser.json'
          : 'react or react-native source, kept for the docs URLs, cannot be run in this repository',
      };
    } else {
      problems.push(`marker ${snippet.id} in ${snippet.file} belongs to no step`);
    }
  }
  for (const def of reg.ordered()) {
    if (def.kind === 'stub') {
      entries[def.id] = {
        file: null,
        step: def.id,
        role: def.keyset,
        phase: def.phase,
        mode: 'stub',
        reason: def.skipIf ?? null,
      };
      continue;
    }
    for (const id of def.snippets) {
      if (!seen.has(id)) problems.push(`step ${def.id} declares snippet ${id}, but no marker defines it`);
      else if (entries[id]?.step !== def.id)
        problems.push(
          `snippet ${id} is declared by step ${def.id} but its marker sits in ${entries[id]?.step ?? 'no step'}`,
        );
    }
  }
  const sorted = Object.fromEntries(
    Object.keys(entries)
      .sort()
      .map((id) => [id, entries[id]]),
  );
  return {
    manifest: {
      $comment:
        'Generated by npm run docs-snippets:manifest. Do not edit. One entry per snippet id: how the live suite covers it.',
      snippets: sorted,
    },
    problems,
  };
}

export function serialize(manifest: Manifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/** Snippet ids the JavaScript docs pages use, from their EmbeddedCode tags. Undefined when the dir is absent. */
export function docsIds(docsDir: string): { ids: Map<string, string[]>; files: number } | undefined {
  const root = path.join(docsDir, 'docs', 'sdks', 'javascript');
  if (!fs.existsSync(root)) return undefined;
  const ids = new Map<string, string[]>();
  let files = 0;
  const add = (id: string, where: string): void => {
    ids.set(id, [...(ids.get(id) ?? []), where]);
  };
  const walk = (dir: string): string[] =>
    fs
      .readdirSync(dir, { withFileTypes: true })
      .flatMap((e) =>
        e.isDirectory() ? walk(path.join(dir, e.name)) : /\.mdx?$/.test(e.name) ? [path.join(dir, e.name)] : [],
      );
  for (const file of walk(root)) {
    files += 1;
    const rel = path.relative(docsDir, file);
    const text = fs.readFileSync(file, 'utf8');
    // Only EmbeddedCode tags with a JavaScript SDK repository URL count.
    for (const tag of text.matchAll(/<EmbeddedCode\b[\s\S]*?\/>/g)) {
      if (!/pubnub\/javascript\//.test(tag[0])) continue;
      const list = /snippets=\{\[([^\]]*)\]\}/.exec(tag[0]);
      const single = /snippet=\{?['"]([^'"]+)['"]\}?/.exec(tag[0]);
      const found = list ? [...list[1].matchAll(/['"]([^'"]+)['"]/g)].map((m) => m[1]) : single ? [single[1]] : [];
      for (const id of found) add(id, rel);
    }
  }
  return { ids, files };
}
